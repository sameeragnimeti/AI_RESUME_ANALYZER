import { useState } from 'react'
import { Link } from 'react-router-dom'
import { Loader2, Download, ChevronDown, ChevronUp, AlertCircle, CheckCircle2, Rocket, Globe } from 'lucide-react'
import { analyzeApi, AnalyzeResponse } from '../api/client'
import { useAuth } from '../context/AuthContext'
import FileUpload from '../components/FileUpload'
import {
  BarChart, Bar, XAxis, YAxis, CartesianGrid, Tooltip, Cell,
  PieChart, Pie, ResponsiveContainer,
} from 'recharts'

const SCORE_COLORS: Record<string, string> = {
  Excellent: '#059669',
  Good: '#2563eb',
  Average: '#d97706',
  Poor: '#dc2626',
}

function generateReportText(result: AnalyzeResponse): string {
  const { ats, job_prediction, suggestions, parsed } = result
  const { primary } = job_prediction
  const lines = [
    '='.repeat(60),
    '  AI RESUME ANALYZER PRO - ANALYSIS REPORT',
    '='.repeat(60),
    '',
    `ATS Score: ${ats.score}/100  |  ${ats.rating}`,
    '',
    '-'.repeat(60),
    'SCORE BREAKDOWN',
    '-'.repeat(60),
    ...Object.entries(ats.breakdown).map(([s, v]) => `  ${s}: ${v}`),
    '',
    '-'.repeat(60),
    'PREDICTED JOB ROLE',
    '-'.repeat(60),
    `  Primary: ${primary.role} (${primary.score}% match)`,
    ...job_prediction.alternatives.map((a) => `  Alternative: ${a.role} (${a.score}% match)`),
    '',
    '-'.repeat(60),
    'SKILLS FOUND',
    '-'.repeat(60),
    ...parsed.skills.map((s) => `  + ${s}`),
    '',
    '-'.repeat(60),
    'MISSING KEYWORDS',
    '-'.repeat(60),
    ...ats.missing_keywords.map((k) => `  - ${k}`),
    '',
    '-'.repeat(60),
    'SUGGESTIONS',
    '-'.repeat(60),
    ...suggestions.map((s) => `  * ${s}`),
    '',
    '-'.repeat(60),
    'RESUME STATS',
    '-'.repeat(60),
    `  Word Count: ${parsed.word_count}`,
    `  Experience: ${parsed.experience_years} years`,
    `  Education: ${parsed.education.join(', ') || 'Not detected'}`,
    `  Certifications: ${parsed.certifications.join(', ') || 'None'}`,
    '',
    '='.repeat(60),
    '  Generated by AI Resume Analyzer Pro',
    '='.repeat(60),
  ]
  return lines.join('\n')
}

export default function Analyzer() {
  const { user } = useAuth()
  const [file, setFile] = useState<File | null>(null)
  const [loading, setLoading] = useState(false)
  const [result, setResult] = useState<AnalyzeResponse | null>(null)
  const [error, setError] = useState('')
  const [showText, setShowText] = useState(false)

  const handleUpload = async () => {
    if (!file) return
    setLoading(true)
    setError('')
    setResult(null)
    try {
      const data = await analyzeApi.upload(file, user?.username)
      setResult(data)
    } catch (e: unknown) {
      setError(e instanceof Error ? e.message : 'Analysis failed')
    } finally {
      setLoading(false)
    }
  }

  if (!result) {
    return (
      <div className="page-transition max-w-2xl mx-auto">
        <div className="gradient-banner text-center mb-8">
          <h1 className="text-xl font-bold">Resume Analyzer</h1>
          <p className="text-white/80 text-sm mt-1">Upload your resume for AI-powered ATS analysis</p>
        </div>

        <FileUpload onFileSelect={setFile} />

        <button
          onClick={handleUpload}
          disabled={!file || loading}
          className="btn-primary w-full mt-6 flex items-center justify-center gap-2"
        >
          {loading ? (
            <>
              <Loader2 size={18} className="animate-spin" /> Analyzing...
            </>
          ) : (
            'Analyze Resume'
          )}
        </button>

        {error && (
          <div className="mt-4 flex items-center gap-2 text-sm text-red-600 bg-red-50 p-3 rounded-xl">
            <AlertCircle size={16} /> {error}
          </div>
        )}
      </div>
    )
  }

  const { ats, job_prediction, suggestions, parsed } = result
  const ratingColor = SCORE_COLORS[ats.rating] || '#64748b'
  const breakdownData = Object.entries(ats.breakdown).map(([name, value]) => ({ name, value }))
  const skillCount = parsed.skills.length
  const pieData = [
    { name: 'Skills Found', value: skillCount },
    { name: 'Growth Areas', value: Math.max(0, 20 - skillCount) },
  ]

  return (
    <div className="page-transition">
      <div className="gradient-banner text-center mb-8">
        <h1 className="text-xl font-bold">Analysis Complete</h1>
        <p className="text-white/80 text-sm mt-1">Your resume has been analyzed successfully</p>
      </div>

      <div className="flex flex-col items-center mb-8">
        <div
          className="w-36 h-36 rounded-full flex items-center justify-center text-5xl font-extrabold text-white shadow-xl"
          style={{ background: `linear-gradient(135deg, ${ratingColor}, ${ratingColor}bb)` }}
        >
          {ats.score}
        </div>
        <div className="mt-3 flex items-center gap-2">
          <span
            className="px-3 py-1 rounded-full text-sm font-semibold"
            style={{ background: `${ratingColor}18`, color: ratingColor }}
          >
            {ats.rating} &middot; {ats.score}/100
          </span>
        </div>
      </div>

      <div className="grid grid-cols-2 sm:grid-cols-4 gap-4 mb-8">
        {[
          ['Skills Found', parsed.skills.length, '#2563eb'],
          ['Experience', parsed.experience_years ? `${parsed.experience_years} yrs` : 'N/A', '#059669'],
          ['Word Count', parsed.word_count, '#d97706'],
          ['Certifications', parsed.certifications.length || 0, '#7c3aed'],
        ].map(([label, value, color]) => (
          <div key={String(label)} className="card !p-4 text-center">
            <p className="text-xs text-slate-500 font-medium mb-1">{String(label)}</p>
            <p className="text-2xl font-extrabold" style={{ color: String(color) }}>
              {value as string | number}
            </p>
          </div>
        ))}
      </div>

      <div className="grid md:grid-cols-2 gap-6 mb-8">
        <div className="card">
          <h3 className="font-bold text-slate-800 mb-4">ATS Score Breakdown</h3>
          <ResponsiveContainer width="100%" height={280}>
            <BarChart data={breakdownData} margin={{ top: 5, right: 10, left: -10, bottom: 5 }}>
              <CartesianGrid strokeDasharray="3 3" stroke="#f1f5f9" />
              <XAxis dataKey="name" tick={{ fontSize: 11 }} interval={0} angle={-20} textAnchor="end" height={60} />
              <YAxis domain={[0, 25]} tick={{ fontSize: 11 }} />
              <Tooltip contentStyle={{ borderRadius: 12, border: '1px solid #e2e8f0', fontSize: 13 }} />
              <Bar dataKey="value" radius={[4, 4, 0, 0]}>
                {breakdownData.map((_, i) => (
                  <Cell key={i} fill={`hsl(217, ${70 + i * 3}%, ${50 - i * 2}%)`} />
                ))}
              </Bar>
            </BarChart>
          </ResponsiveContainer>
        </div>

        <div className="card">
          <h3 className="font-bold text-slate-800 mb-4">Skills Coverage</h3>
          <ResponsiveContainer width="100%" height={280}>
            <PieChart>
              <Pie
                data={pieData}
                cx="50%"
                cy="50%"
                innerRadius={70}
                outerRadius={110}
                paddingAngle={4}
                dataKey="value"
                startAngle={90}
                endAngle={-270}
              >
                <Cell fill="#2563eb" />
                <Cell fill="#f1f5f9" />
              </Pie>
              <Tooltip contentStyle={{ borderRadius: 12, border: '1px solid #e2e8f0' }} />
            </PieChart>
          </ResponsiveContainer>
          <p className="text-center text-sm text-slate-500 -mt-4">
            <strong className="text-primary-600">{skillCount}</strong> / 20 skills
          </p>
        </div>
      </div>

      <div className="grid md:grid-cols-2 gap-6 mb-8">
        <div className="card">
          <h3 className="font-bold text-slate-800 mb-3">Skills Detected</h3>
          <div className="flex flex-wrap gap-1.5">
            {parsed.skills.length > 0 ? (
              parsed.skills.map((s) => <span key={s} className="skill-chip">{s}</span>)
            ) : (
              <p className="text-sm text-slate-400">No skills detected</p>
            )}
          </div>
        </div>

        <div className="card">
          <h3 className="font-bold text-slate-800 mb-3">Missing Keywords</h3>
          <div className="flex flex-wrap gap-1.5">
            {ats.missing_keywords.length > 0 ? (
              ats.missing_keywords.map((k) => <span key={k} className="skill-chip-missing">{k}</span>)
            ) : (
              <p className="text-sm text-emerald-600 flex items-center gap-1.5">
                <CheckCircle2 size={16} /> Great coverage!
              </p>
            )}
          </div>
        </div>
      </div>

      <div className="card mb-8">
        <h3 className="font-bold text-slate-800 mb-4">Predicted Job Role</h3>
        {job_prediction.primary.score > 0 ? (
          <>
            <div className="flex items-center justify-between p-4 bg-slate-50 rounded-xl">
              <div>
                <p className="text-xs text-slate-500 font-medium">Primary Match</p>
                <p className="text-xl font-bold text-slate-800 mt-0.5">{job_prediction.primary.role}</p>
                <p className="text-xs text-slate-400">
                  {job_prediction.primary.matched_skills.length} skills matched
                </p>
              </div>
              <span className="text-3xl font-extrabold text-primary-600">{job_prediction.primary.score}%</span>
            </div>
            {job_prediction.alternatives.length > 0 && (
              <div className="mt-4 space-y-2">
                <p className="text-sm font-medium text-slate-500">Alternatives</p>
                {job_prediction.alternatives.map((alt) => (
                  <div
                    key={alt.role}
                    className="flex justify-between items-center p-3 rounded-xl bg-white border border-slate-100"
                  >
                    <span className="text-sm font-medium text-slate-600">{alt.role}</span>
                    <span className="text-sm font-bold text-primary-600">{alt.score}%</span>
                  </div>
                ))}
              </div>
            )}
          </>
        ) : (
          <p className="text-slate-400 text-sm">Could not predict a specific role</p>
        )}
      </div>

      <div className="card mb-8">
        <h3 className="font-bold text-slate-800 mb-4">AI Suggestions</h3>
        <div className="space-y-2">
          {suggestions.map((s, i) => (
            <div key={i} className="suggestion-item">{s}</div>
          ))}
        </div>
      </div>

      <div className="grid sm:grid-cols-2 gap-4 mb-8">
        <Link
          to="/job-recommendations"
          className="card group hover:border-purple-300 text-center"
        >
          <div className="w-12 h-12 rounded-2xl bg-purple-50 text-purple-600 flex items-center justify-center mx-auto mb-3 group-hover:scale-110 transition-transform">
            <Rocket size={24} />
          </div>
          <h3 className="font-bold text-slate-800 group-hover:text-purple-600 transition-colors">
            Get Job Matches
          </h3>
          <p className="text-sm text-slate-500 mt-1">
            Upload resume for AI-powered job recommendations with skill gap analysis
          </p>
        </Link>
        <Link
          to="/job-portals"
          className="card group hover:border-blue-300 text-center"
        >
          <div className="w-12 h-12 rounded-2xl bg-blue-50 text-blue-600 flex items-center justify-center mx-auto mb-3 group-hover:scale-110 transition-transform">
            <Globe size={24} />
          </div>
          <h3 className="font-bold text-slate-800 group-hover:text-blue-600 transition-colors">
            Browse Job Portals
          </h3>
          <p className="text-sm text-slate-500 mt-1">
            Explore 50+ curated job platforms across multiple categories
          </p>
        </Link>
      </div>

      <div className="flex flex-col sm:flex-row gap-3 mb-6">
        <button
          onClick={() => {
            const text = generateReportText(result)
            const blob = new Blob([text], { type: 'text/plain' })
            const url = URL.createObjectURL(blob)
            const a = document.createElement('a')
            a.href = url
            a.download = `Resume_Report_${ats.score}pts.txt`
            a.click()
            URL.revokeObjectURL(url)
          }}
          className="btn-primary flex-1 flex items-center justify-center gap-2"
        >
          <Download size={16} /> Download TXT Report
        </button>
        <button
          onClick={() => setShowText(!showText)}
          className="btn-secondary flex-1 flex items-center justify-center gap-2"
        >
          {showText ? <ChevronUp size={16} /> : <ChevronDown size={16} />}
          {showText ? 'Hide' : 'View'} Extracted Text
        </button>
      </div>

      {showText && parsed.text_preview && (
        <div className="card mb-6">
          <h3 className="font-bold text-slate-800 mb-3">Extracted Text Preview</h3>
          <pre className="text-sm text-slate-600 whitespace-pre-wrap bg-slate-50 p-4 rounded-xl max-h-60 overflow-y-auto">
            {parsed.text_preview}
          </pre>
        </div>
      )}
    </div>
  )
}