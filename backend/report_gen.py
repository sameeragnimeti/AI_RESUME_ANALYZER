import io
import re
from datetime import datetime

try:
    from fpdf import FPDF
    HAS_FPDF = True
except ImportError:
    HAS_FPDF = False


def _clean_text(text):
    replacements = {
        "\u2014": "-", "\u2013": "-", "\u2018": "'", "\u2019": "'",
        "\u201c": '"', "\u201d": '"', "\u2022": "*", "\u2026": "...",
        "\u00a0": " ", "\u202f": " ", "\u2009": " ",
    }
    for old, new in replacements.items():
        text = text.replace(old, new)
    return re.sub(r'[^\x00-\x7F]+', '', text)


def generate_report_text(parsed_data, ats_result, job_prediction, suggestions):
    lines = [
        "=" * 60,
        "  AI RESUME ANALYZER PRO - ANALYSIS REPORT",
        "=" * 60,
        "",
        f"Date: {datetime.now().strftime('%B %d, %Y at %I:%M %p')}",
        "",
        "-" * 60,
        "ATS SCORE SUMMARY",
        "-" * 60,
        f"  Overall Score: {ats_result['score']}/100",
        f"  Rating: {ats_result['rating']}",
        "",
        "-" * 60,
        "SCORE BREAKDOWN",
        "-" * 60,
    ]
    for section, s in ats_result.get("breakdown", {}).items():
        lines.append(f"  {section}: {s}")
    lines.append("")

    lines.append("-" * 60)
    lines.append("PREDICTED JOB ROLE")
    lines.append("-" * 60)
    primary = job_prediction.get("primary", {})
    lines.append(f"  Primary: {primary.get('role', 'N/A').title()} ({primary.get('score', 0)}% match)")
    for alt in job_prediction.get("alternatives", []):
        lines.append(f"  Alternative: {alt['role'].title()} ({alt['score']}% match)")
    lines.append("")

    skills = parsed_data.get("skills", [])
    if skills:
        lines.append("-" * 60)
        lines.append("SKILLS FOUND")
        lines.append("-" * 60)
        for s in skills:
            lines.append(f"  + {s.title()}")
        lines.append("")

    missing = ats_result.get("missing_keywords", [])
    if missing:
        lines.append("-" * 60)
        lines.append("MISSING KEYWORDS")
        lines.append("-" * 60)
        for m in missing:
            lines.append(f"  - {m}")
        lines.append("")

    if suggestions:
        lines.append("-" * 60)
        lines.append("AI SUGGESTIONS")
        lines.append("-" * 60)
        for s in suggestions:
            lines.append(f"  * {s}")
        lines.append("")

    lines.append("-" * 60)
    lines.append("RESUME STATS")
    lines.append("-" * 60)
    lines.append(f"  Word Count: {parsed_data.get('word_count', 'N/A')}")
    lines.append(f"  Experience: {parsed_data.get('experience_years', 0)} years")
    lines.append(f"  Education: {', '.join(parsed_data.get('education', [])) or 'Not detected'}")
    lines.append(f"  Certifications: {', '.join(parsed_data.get('certifications', [])) or 'None detected'}")
    lines.append("")

    contact = parsed_data.get("contact", {})
    lines.append("-" * 60)
    lines.append("CONTACT INFO DETECTED")
    lines.append("-" * 60)
    lines.append(f"  Emails: {', '.join(contact.get('emails', [])) or 'None detected'}")
    lines.append(f"  Phones: {', '.join(contact.get('phones', [])) or 'None detected'}")
    lines.append("")
    lines.append("=" * 60)
    lines.append("  Generated by AI Resume Analyzer Pro")
    lines.append("=" * 60)

    return "\n".join(lines)


def generate_pdf(parsed_data, ats_result, job_prediction, suggestions):
    if not HAS_FPDF:
        return None

    pdf = FPDF()
    pdf.add_page()

    def wc(txt):
        pdf.cell(0, 6, _clean_text(str(txt)), new_x="LMARGIN", new_y="NEXT")

    pdf.set_font("Helvetica", "B", 20)
    pdf.set_text_color(37, 99, 235)
    wc("AI Resume Analyzer Pro")
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(100, 116, 139)
    wc("ATS Analysis Report")
    pdf.ln(10)

    pdf.set_font("Helvetica", "B", 14)
    pdf.set_text_color(15, 23, 42)
    wc(f"ATS Score: {ats_result['score']}/100 | {ats_result['rating']}")
    pdf.ln(5)

    pdf.set_font("Helvetica", "B", 12)
    pdf.set_text_color(37, 99, 235)
    wc("Score Breakdown")
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(51, 65, 85)
    for section, s in ats_result.get("breakdown", {}).items():
        wc(f"  {section}: {s}")
    pdf.ln(5)

    primary = job_prediction.get("primary", {})
    if primary and primary.get("score", 0) > 0:
        pdf.set_font("Helvetica", "B", 12)
        pdf.set_text_color(37, 99, 235)
        wc("Predicted Job Role")
        pdf.set_font("Helvetica", "", 10)
        pdf.set_text_color(51, 65, 85)
        wc(f"  Primary: {primary['role'].title()} ({primary['score']}% match)")
        for alt in job_prediction.get("alternatives", []):
            wc(f"  Alternative: {alt['role'].title()} ({alt['score']}% match)")
        pdf.ln(5)

    skills = parsed_data.get("skills", [])
    if skills:
        pdf.set_font("Helvetica", "B", 12)
        pdf.set_text_color(37, 99, 235)
        wc("Skills Found")
        pdf.set_font("Helvetica", "", 10)
        pdf.set_text_color(51, 65, 85)
        wc(", ".join(s.title() for s in skills))
        pdf.ln(5)

    if suggestions:
        pdf.set_font("Helvetica", "B", 12)
        pdf.set_text_color(37, 99, 235)
        wc("Suggestions")
        pdf.set_font("Helvetica", "", 10)
        pdf.set_text_color(51, 65, 85)
        for s in suggestions:
            wc(f"  * {s}")
        pdf.ln(5)

    pdf.set_font("Helvetica", "I", 8)
    pdf.set_text_color(148, 163, 184)
    wc(f"Generated by AI Resume Analyzer Pro on {datetime.now().strftime('%B %d, %Y')}")

    return bytes(pdf.output())
